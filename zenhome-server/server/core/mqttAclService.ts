import crypto from 'crypto';

export interface HubMqttCredentials {
  username: string;
  password: string;
  homeId: string;
  macAddress: string;
  baseTopic: string;
  allowedPublishTopics: string[];
  allowedSubscribeTopics: string[];
  aclConfigText: string;
  createdAt: string;
}

/**
 * Khởi tạo thông tin xác thực MQTT độc lập (Per-Hub Credentials) và cấu hình ACL giới hạn quyền tối thiểu
 * @param mac Địa chỉ MAC phần cứng của ESP32 Hub
 * @param homeId Mã định danh ngôi nhà hoặc tài khoản sở hữu
 */
export function generateHubMqttCredentials(mac: string, homeId: string): HubMqttCredentials {
  if (!mac || !homeId) {
    throw new Error('Cần cung cấp đầy đủ mac và homeId để khởi tạo MQTT ACL.');
  }

  const cleanMac = mac.replace(/[:\-]/g, '').toUpperCase();
  const cleanHome = homeId.trim().replace(/[^a-zA-Z0-9_-]/g, '_');
  
  // Tên tài khoản định danh duy nhất cho từng Hub
  const username = `hub_${cleanMac.toLowerCase()}`;
  
  // Mật khẩu ngẫu nhiên an toàn 256-bit CSPRNG
  const password = crypto.randomBytes(24).toString('base64url');

  const baseTopic = `zenhome/${cleanHome}/${cleanMac}`;
  const legacyBaseTopic = `${cleanHome}/${cleanMac}`;

  // Các topic Hub được phép phát (Publish) trạng thái và cảnh báo
  const allowedPublishTopics = [
    `${baseTopic}/#`,
    `${legacyBaseTopic}/system/ota_progress`,
    `${legacyBaseTopic}/system/ota_result`,
    `${legacyBaseTopic}/system/event`,
    `${legacyBaseTopic}/+/+/state`,
    `${legacyBaseTopic}/nhiet_do_trong_nha`,
    `${legacyBaseTopic}/esp_status`,
    `${legacyBaseTopic}/heartbeat`,
    `${legacyBaseTopic}/sync/report`,
  ];

  // Các topic Hub được phép lắng nghe (Subscribe) lệnh điều khiển
  const allowedSubscribeTopics = [
    `${baseTopic}/#`,
    `${legacyBaseTopic}/system/ota_update`,
    `${legacyBaseTopic}/system/config`,
    `${legacyBaseTopic}/system/members`,
    `${legacyBaseTopic}/system/reset`,
    `${legacyBaseTopic}/+/+/cmd`,
    `${legacyBaseTopic}/+/+/schedule`,
    `${legacyBaseTopic}/+/+/timer_on`,
    `${legacyBaseTopic}/+/+/timer_off`,
  ];

  // Cấu hình ACL chuẩn định dạng Mosquitto / EMQX / HiveMQ
  const aclConfigText = `# ==============================================================================
# MQTT ACL Rule for Hub: ${cleanMac} (Home: ${cleanHome})
# Auto-generated by ZenHome Cloud Security Subsystem
# ==============================================================================
user ${username}
topic read ${legacyBaseTopic}/system/#
topic read ${legacyBaseTopic}/+/+/cmd
topic read ${legacyBaseTopic}/+/+/schedule
topic read ${legacyBaseTopic}/+/+/timer_on
topic read ${legacyBaseTopic}/+/+/timer_off
topic read ${baseTopic}/#
topic write ${legacyBaseTopic}/system/#
topic write ${legacyBaseTopic}/+/+/state
topic write ${legacyBaseTopic}/nhiet_do_trong_nha
topic write ${legacyBaseTopic}/esp_status
topic write ${legacyBaseTopic}/heartbeat
topic write ${legacyBaseTopic}/sync/report
topic write ${baseTopic}/#
`;

  return {
    username,
    password,
    homeId: cleanHome,
    macAddress: cleanMac,
    baseTopic,
    allowedPublishTopics,
    allowedSubscribeTopics,
    aclConfigText,
    createdAt: new Date().toISOString(),
  };
}

/**
 * Kiểm tra tính hợp lệ của quyền truy cập topic theo tài khoản Hub (Software-Level ACL Validator)
 * @param username Tên tài khoản Hub MQTT
 * @param topic Topic đang phát hoặc đăng ký
 * @param action 'pub' | 'sub'
 */
export function validateHubTopicAccess(username: string, topic: string, action: 'pub' | 'sub'): boolean {
  if (!username || !topic) return false;
  if (!username.startsWith('hub_')) return true; // Tài khoản server hoặc admin không bị giới hạn theo quy tắc per-hub

  const macFromUser = username.replace(/^hub_/, '').toUpperCase();
  const cleanTopic = topic.replace(/[:\-]/g, '');

  // Bắt buộc topic phải chứa đúng MAC của Hub
  if (!cleanTopic.toUpperCase().includes(macFromUser)) {
    return false;
  }

  return true;
}
