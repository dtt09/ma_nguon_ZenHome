const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT_DIR = path.resolve(__dirname, '..');
const KEYS_DIR = path.join(ROOT_DIR, 'scripts', 'keys');
const PRIV_KEY_PATH = path.join(KEYS_DIR, 'firmware_signer_private.pem');
const PUB_KEY_PATH = path.join(KEYS_DIR, 'firmware_signer_public.pem');
const ESP_HEADER_PATH = path.join(ROOT_DIR, 'esp32_1', 'include', 'firmware_signer_pubkey.h');

if (!fs.existsSync(KEYS_DIR)) {
  fs.mkdirSync(KEYS_DIR, { recursive: true });
}

function ensureKeysExist() {
  if (fs.existsSync(PRIV_KEY_PATH) && fs.existsSync(PUB_KEY_PATH)) {
    console.log('🔑 Đã tìm thấy cặp khóa ký số ECDSA P-256 có sẵn tại:', KEYS_DIR);
    return;
  }

  console.log('⚙️  Đang khởi tạo cặp khóa mật mã phi đối xứng ECDSA P-256 (NIST P-256 / prime256v1)...');
  const { publicKey, privateKey } = crypto.generateKeyPairSync('ec', {
    namedCurve: 'prime256v1',
    publicKeyEncoding: { type: 'spki', format: 'pem' },
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' }
  });

  fs.writeFileSync(PRIV_KEY_PATH, privateKey, { encoding: 'utf8', mode: 0o600 });
  fs.writeFileSync(PUB_KEY_PATH, publicKey, { encoding: 'utf8', mode: 0o644 });
  console.log('   ✅ Đã tạo Private Key:', PRIV_KEY_PATH);
  console.log('   ✅ Đã tạo Public Key: ', PUB_KEY_PATH);
}

function generateCppHeader() {
  const pubPem = fs.readFileSync(PUB_KEY_PATH, 'utf8').trim();
  
  // Format as C string literal
  const lines = pubPem.split('\n').map(l => `  "${l}\\n"`).join('\n');

  const headerContent = `// ============================================================================
// 🔐 ZENHOME HARDWARE SECURITY - OFFICIAL DEVELOPER FIRMWARE SIGNER PUBLIC KEY
// Auto-generated by scripts/generate_firmware_keys.js
// Algorithm: ECDSA NIST P-256 (prime256v1) with SHA-256 Hash Digest
// ============================================================================
#ifndef FIRMWARE_SIGNER_PUBKEY_H
#define FIRMWARE_SIGNER_PUBKEY_H

#include <pgmspace.h>

static const char FIRMWARE_SIGNER_PUBLIC_KEY[] PROGMEM = 
${lines};

#endif // FIRMWARE_SIGNER_PUBKEY_H
`;

  fs.writeFileSync(ESP_HEADER_PATH, headerContent, 'utf8');
  console.log('   ✅ Đã cập nhật Header Public Key cho ESP32:', ESP_HEADER_PATH);
}

function signFirmwareBinary(binPath) {
  if (!fs.existsSync(binPath)) {
    throw new Error(`Không tìm thấy file nhị phân: ${binPath}`);
  }
  const fileBuf = fs.readFileSync(binPath);
  const sha256 = crypto.createHash('sha256').update(fileBuf).digest('hex').toUpperCase();

  const privKey = fs.readFileSync(PRIV_KEY_PATH, 'utf8');
  const sign = crypto.createSign('SHA256');
  sign.update(fileBuf);
  const derSig = sign.sign(privKey);
  const sigHex = derSig.toString('hex').toLowerCase();

  return {
    sha256,
    sigHex,
    fileSize: fileBuf.length
  };
}

function verifyFirmwareSignature(binPath, sigHex) {
  const fileBuf = fs.readFileSync(binPath);
  const pubKey = fs.readFileSync(PUB_KEY_PATH, 'utf8');
  const verify = crypto.createVerify('SHA256');
  verify.update(fileBuf);
  return verify.verify(pubKey, Buffer.from(sigHex, 'hex'));
}

if (require.main === module) {
  ensureKeysExist();
  generateCppHeader();

  const fwPath = path.join(ROOT_DIR, 'firmware.bin');
  if (fs.existsSync(fwPath)) {
    const res = signFirmwareBinary(fwPath);
    console.log('\n🔍 THỬ NGHIỆM KÝ SỐ FIRMWARE HIỆN TẠI (firmware.bin):');
    console.log('   - Kích thước:  ', res.fileSize, 'bytes');
    console.log('   - SHA-256:     ', res.sha256);
    console.log('   - Chữ ký ECDSA:', res.sigHex.substring(0, 32) + '...' + res.sigHex.substring(res.sigHex.length - 16));
    const verified = verifyFirmwareSignature(fwPath, res.sigHex);
    console.log('   - Xác thực mẫu: ', verified ? '✅ HỢP LỆ 100%' : '❌ KHÔNG HỢP LỆ');
  }
}

module.exports = {
  ensureKeysExist,
  generateCppHeader,
  signFirmwareBinary,
  verifyFirmwareSignature,
  PRIV_KEY_PATH,
  PUB_KEY_PATH
};
